"""
Property-based checks of the combinatorial VCG mechanism.

Random multi-unit instances (OR and XOR bidding) are generated by Hypothesis
and checked for: feasibility, optimality against brute force, individual
rationality, non-negative payments and dominant-strategy truthfulness.
"""

import random

import pytest
from hypothesis import HealthCheck, given, settings
from hypothesis import strategies as st

from backend.app.auction.engine import (
    AuctionEngine,
    Bid,
    Resource,
    SolverMethod,
    enumerate_allocations,
    is_feasible,
    solve_exhaustive,
    solve_greedy,
    solve_wdp_lp,
)
from compute_bazaar.mechanism import best_deviation_gain, random_instance, run_vcg

EPS = 1e-6
seeds = st.integers(min_value=0, max_value=2**32 - 1)
FAST = settings(max_examples=60, deadline=None, suppress_health_check=[HealthCheck.too_slow])


@FAST
@given(seed=seeds, xor=st.booleans())
def test_exhaustive_matches_brute_force_enumeration(seed, xor):
    inst = random_instance(random.Random(seed), n_agents=3, xor_per_agent=xor)
    winners, value = solve_exhaustive(inst.true_bids, inst.resources, xor)
    best = max(sum(b.bid_amount for b in alloc) for alloc in enumerate_allocations(inst.true_bids, inst.resources, xor))
    assert is_feasible(winners, inst.resources, xor)
    assert value == pytest.approx(best, abs=EPS)


@FAST
@given(seed=seeds, xor=st.booleans())
def test_greedy_is_feasible_and_never_beats_optimum(seed, xor):
    inst = random_instance(random.Random(seed), xor_per_agent=xor)
    g_winners, g_value = solve_greedy(inst.true_bids, inst.resources, xor)
    _, opt = solve_exhaustive(inst.true_bids, inst.resources, xor)
    assert is_feasible(g_winners, inst.resources, xor)
    assert g_value <= opt + EPS


@settings(max_examples=15, deadline=None)
@given(seed=seeds, xor=st.booleans())
def test_ilp_matches_exhaustive_optimum(seed, xor):
    inst = random_instance(random.Random(seed), n_agents=5, xor_per_agent=xor)
    lp_winners, lp_value = solve_wdp_lp(inst.true_bids, inst.resources, xor)
    _, ex_value = solve_exhaustive(inst.true_bids, inst.resources, xor)
    assert is_feasible(lp_winners, inst.resources, xor)
    assert lp_value == pytest.approx(ex_value, abs=1e-4)


@FAST
@given(seed=seeds, xor=st.booleans())
def test_payments_are_individually_rational_and_non_negative(seed, xor):
    inst = random_instance(random.Random(seed), n_agents=5, xor_per_agent=xor)
    winners, payments, _ = run_vcg(inst, inst.true_bids)
    for agent, p in payments.items():
        won = sum(b.bid_amount for b in winners if b.agent_id == agent)
        assert -EPS <= p <= won + EPS


@settings(max_examples=40, deadline=None, suppress_health_check=[HealthCheck.too_slow])
@given(seed=seeds, xor=st.booleans())
def test_truthful_reporting_is_a_dominant_strategy(seed, xor):
    inst = random_instance(random.Random(seed), n_agents=4, xor_per_agent=xor)
    for agent in inst.agents:
        assert best_deviation_gain(inst, agent) <= 1e-4


def test_multi_bid_agent_pays_full_externality():
    """
    Regression for per-bid VCG. Agent A bids twice for the same single GPU
    ($100 and $90), B bids $50. A wins with $100. Removing only that bid
    leaves A's own $90 bid as the "competition", so per-bid VCG charged
    A $90. True VCG removes all of A's bids: A owes B's $50 externality.
    """
    resources = [Resource("GPU", "gpu")]
    engine = AuctionEngine(resources)
    engine.submit_bid(Bid("a1", "A", ["GPU"], 100.0))
    engine.submit_bid(Bid("a2", "A", ["GPU"], 90.0))
    engine.submit_bid(Bid("b1", "B", ["GPU"], 50.0))
    result = engine.run_auction()
    assert [w.bid_id for w in result.winning_bids] == ["a1"]
    assert result.agent_payments == {"A": pytest.approx(50.0)}


def test_multi_unit_capacity_allows_several_winners():
    resources = [Resource("GPU", "gpu", units=3)]
    engine = AuctionEngine(resources)
    engine.submit_bid(Bid("a", "A", ["GPU"], 40.0, quantities={"GPU": 2}))
    engine.submit_bid(Bid("b", "B", ["GPU"], 30.0))
    engine.submit_bid(Bid("c", "C", ["GPU"], 20.0))
    result = engine.run_auction()
    assert {w.bid_id for w in result.winning_bids} == {"a", "b"}
    assert result.units_used == {"GPU": 3}
    # A displaces C (20); B displaces C (20) too, since A+C needs only 3 units.
    assert result.agent_payments["A"] == pytest.approx(20.0)
    assert result.agent_payments["B"] == pytest.approx(20.0)


def test_xor_per_agent_limits_each_agent_to_one_bid():
    resources = [Resource("GPU", "gpu"), Resource("CPU", "cpu")]
    engine = AuctionEngine(resources, xor_per_agent=True)
    engine.submit_bid(Bid("a1", "A", ["GPU"], 60.0))
    engine.submit_bid(Bid("a2", "A", ["CPU"], 50.0))
    engine.submit_bid(Bid("b1", "B", ["CPU"], 10.0))
    result = engine.run_auction()
    assert sorted(w.bid_id for w in result.winning_bids) == ["a1", "b1"]


def test_demand_above_supply_is_rejected():
    engine = AuctionEngine([Resource("GPU", "gpu", units=2)])
    assert engine.submit_bid(Bid("a", "A", ["GPU"], 10.0, quantities={"GPU": 3})) is False


def test_exhaustive_solver_method_runs_end_to_end():
    engine = AuctionEngine([Resource("GPU", "gpu")], method=SolverMethod.EXHAUSTIVE)
    engine.submit_bid(Bid("a", "A", ["GPU"], 10.0))
    engine.submit_bid(Bid("b", "B", ["GPU"], 7.0))
    result = engine.run_auction()
    assert result.payments == {"a": pytest.approx(7.0)}
